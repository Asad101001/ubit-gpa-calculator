# ── 2. Read .env for Supabase Credentials ─────────────────────────────────────
supabase_url = ""
supabase_key = ""

with open('.env', 'r', encoding='utf-8') as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith('#'): continue
        k, v = line.split('=', 1)
        v = v.strip().strip('\'"')
        if k == 'VITE_SUPABASE_URL': supabase_url = v
        if k == 'VITE_SUPABASE_ANON_KEY': supabase_key = v

print(f"Connecting to Supabase at: {supabase_url}")

# ── 3. Read and Update public/fallback-results.json ───────────────────────────
with open('public/fallback-results.json', 'r', encoding='utf-8') as f:
    records = json.load(f)

print(f"Loaded {len(records)} existing Section A records from fallback-results.json.")

now_iso = datetime.now(timezone.utc).isoformat()
updated_count = 0

for student in records:
    seat = student.get('seat_no')
    if not seat: continue
    
    changed = False
    
    if seat in PDF3_CS451:
        new_val = str(PDF3_CS451[seat])
        if student.get('cs451') != new_val:
            student['cs451'] = new_val
            changed = True
            
    if seat in PDF1_CS455:
        new_val = str(PDF1_CS455[seat])
        if student.get('cs455') != new_val:
            student['cs455'] = new_val
            changed = True
            
    if seat in PDF2_CS459:
        new_val = str(PDF2_CS459[seat])
        if student.get('cs459') != new_val:
            student['cs459'] = new_val
            changed = True

    if changed:
        student['updated_at'] = now_iso
        updated_count += 1

# Write back sorted fallback-results.json
records.sort(key=lambda s: s.get('seat_no', ''))
with open('public/fallback-results.json', 'w', encoding='utf-8') as f:
    json.dump(records, f, indent=2)

print(f"Updated {updated_count} Section A student records in public/fallback-results.json.")

# ── 4. Update Supabase via REST API for Section A Students ────────────────────
print("\nUpdating Supabase database for Section A students...")
success_db = 0
failed_db = 0

for student in records:
    seat = student.get('seat_no')
    patch_body = {
        'cs451': student.get('cs451', 'Results Unannounced'),
        'cs455': student.get('cs455', 'Results Unannounced'),
        'cs459': student.get('cs459', 'Results Unannounced'),
        'updated_at': now_iso
    }
    
    url = f"{supabase_url}/rest/v1/student_results?seat_no=eq.{seat}"
    req_data = json.dumps(patch_body).encode('utf-8')
    req = urllib.request.Request(
        url,
        data=req_data,
        method='PATCH',
        headers={
            'apikey': supabase_key,
            'Authorization': f'Bearer {supabase_key}',
            'Content-Type': 'application/json',
            'Prefer': 'return=minimal'
        }
    )
    
    try:
        with urllib.request.urlopen(req) as resp:
            if resp.status in (200, 204):
                success_db += 1
            else:
                print(f"Warning: {seat} got status {resp.status}")
                failed_db += 1
    except Exception as e:
        print(f"Error updating {seat} in DB: {e}")
        failed_db += 1

print(f"\nSupabase Update Complete: {success_db} succeeded, {failed_db} failed.")
